import fs from "node:fs";
import assert from "node:assert/strict";
import { parseDocument } from "yaml";
const document = parseDocument(fs.readFileSync(".github/workflows/quality.yml", "utf8"), { uniqueKeys: true });
assert.equal(document.errors.length, 0, "Invalid workflow YAML");
const workflow = document.toJS();
assert.deepEqual(Object.keys(workflow.on).sort(), ["pull_request", "push"]);
assert.deepEqual(workflow.permissions, { contents: "read" });
assert.equal(workflow.jobs.quality["timeout-minutes"], 20);
const steps = workflow.jobs.quality.steps;
for (const step of steps.filter((item) => item.uses)) assert.match(step.uses, /^actions\/(checkout|setup-node)@[a-f0-9]{40}$/);
assert.equal(steps[0].with["persist-credentials"], false);
assert.equal(steps[1].with["node-version-file"], ".nvmrc");
assert.equal(steps[1].with["package-manager-cache"], false);
const pkg = JSON.parse(fs.readFileSync("package.json", "utf8"));
assert.equal(fs.readFileSync(".nvmrc", "utf8").trim(), pkg.engines.node);
assert.equal(fs.readFileSync(".node-version", "utf8").trim(), pkg.engines.node);
assert.equal(pkg.packageManager, "npm@" + pkg.engines.npm);
assert.deepEqual(steps.filter((step) => step.run).map((step) => step.run), ["npm install --global npm@" + pkg.engines.npm, "npm ci --no-audit", "npm run check"]);
assert.equal(workflow.jobs.quality.env.SIGNALPULSE_DATA_MODE, "synthetic");
assert.equal(pkg.scripts.check, "npm run typecheck && npm run lint && npm test && npm run check:boundaries && npm run check:ci && npm run build && npm run check:bundle");
console.log("CI YAML, action pins, read-only permissions, toolchain and quality command checks passed. Remote execution not tested.");
